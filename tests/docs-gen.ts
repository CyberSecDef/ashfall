// Generates the README's entity and trigger reference from the code: entity
// types, families and descriptions from the doc comments in params.ts, fields
// and defaults from the Zod schemas. tests/docs.test.ts fails when the README
// is stale; `npm run docs` rewrites it.

import { readFileSync } from 'node:fs';
import { z } from 'zod';
import { entityParams, type EntityType } from '../src/entities/params';

export const START = '<!-- entity-reference:start (generated by `npm run docs`; do not edit by hand) -->';
export const END = '<!-- entity-reference:end -->';

interface Entry {
  family: string;
  type: EntityType;
  doc: string;
}

function parseSource(): Entry[] {
  const src = readFileSync('src/entities/params.ts', 'utf8');
  const body = src.slice(src.indexOf('export const entityParams = {'), src.indexOf('} as const;'));
  const entries: Entry[] = [];
  let family = 'Level flow';
  let doc = '';
  const lines = body.split('\n');
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i].trim();
    const heading = line.match(/^\/\/ ---- (.+?) -+$/);
    if (heading) {
      family = heading[1].charAt(0).toUpperCase() + heading[1].slice(1);
      continue;
    }
    if (line.startsWith('/**')) {
      let text = line;
      while (!text.includes('*/') && i + 1 < lines.length) text += ' ' + lines[++i].trim();
      doc = text.replace(/\/\*\*|\*\//g, '').replace(/\s\*\s?/g, ' ').replace(/\s+/g, ' ').trim();
      continue;
    }
    const name = line.match(/^([a-z_]+): z\.object\(/);
    if (name && name[1] in entityParams) {
      entries.push({ family, type: name[1] as EntityType, doc });
      doc = '';
    }
  }
  return entries;
}

type JsonProp = { type?: string; default?: unknown; enum?: unknown[]; minimum?: number; maximum?: number; exclusiveMinimum?: number };

function describeParams(type: EntityType): string {
  const schema = z.toJSONSchema(entityParams[type]) as { properties?: Record<string, JsonProp>; required?: string[] };
  const props = schema.properties ?? {};
  const required = new Set(schema.required ?? []);
  const parts = Object.entries(props).map(([name, p]) => {
    let s = `\`${name}\``;
    if (p.enum) s += ` (${p.enum.map((v) => `\`${v}\``).join(' / ')})`;
    if (p.default !== undefined) s += ` = ${JSON.stringify(p.default)}`;
    else if (!required.has(name)) s += '?';
    else s += ' (required)';
    return s;
  });
  return parts.length ? parts.join(', ') : 'none';
}

export function entityReference(): string {
  const entries = parseSource();
  const out: string[] = [START, ''];
  out.push(`Every entity also takes \`x\` (along the path), and optionally \`id\`, \`y\` (defaults to the ground at x) and \`target\` (the id it signals). ${entries.length} types:`);
  let family = '';
  for (const e of entries) {
    if (e.family !== family) {
      family = e.family;
      out.push('', `#### ${family}`, '', '| Type | What it does | Params |', '| --- | --- | --- |');
    }
    out.push(`| \`${e.type}\` | ${e.doc.replace(/\|/g, '\\|')} | ${describeParams(e.type)} |`);
  }
  out.push('', END);
  return out.join('\n');
}

/** Replace the generated section of a README. */
export function splice(readme: string): string {
  const a = readme.indexOf(START);
  const b = readme.indexOf(END);
  if (a < 0 || b < 0) throw new Error('README is missing the entity reference markers');
  return readme.slice(0, a) + entityReference() + readme.slice(b + END.length);
}
